# ---------------------------------------------------------------- markdown matrix
def md_matrix():
    out = ["| # | Source System | Source Table | Source Column | Transformation | Target System | Target Table | Target Column | Mandatory? | Remarks |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    esc = lambda s: str(s).replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")
    cur = None
    for i, (ss, st, sc, tr, tt, tc, m, rem) in enumerate(R, 1):
        tsys = "ELIPS" if tt.startswith("<ELIPS") else ("-" if tt.startswith("(not") else "PAS")
        out.append("| " + " | ".join(esc(x) for x in (i, ss, st, sc, tr, tsys, tt, tc, m, rem)) + " |")
    return "\n".join(out)
