def block(tt, op, desc, src, keys=None, copy_from=None):
    rows = [r for r in R if r[4] == tt]
    maps = []
    for ss, st, sc, tr, _, tc, m, rem in rows:
        if copy_from and st == copy_from and tr.startswith("Copy"):
            maps.append({"source_field": sc, "dest_field": tc, **({"description": rem} if rem else {})})
        else:
            if st == FX: s = "FIX " + sc.split("'")[1] + ": "
            elif st in (EH, ED, ES): s = {EH: "SA header", ED: "SA detail", ES: "SA sub item"}[st] + " " + sc + ": "
            else: s = "" if ss == "Talend" or st in ("-",) else (f"{st}.{sc}: " if sc else f"{st}: ")
            t = tr if tr != "Direct" else ""
            d = (s + t).strip().rstrip(":")
            if rem and m != "Y" or rem and len(d) < 50: d = (d + ("; " if d else "") + rem) if rem else d
            maps.append({"dest_field": tc, "description": d.replace(" *", "")})
    b = {"source": {"table": src}, "destination": {"table": tt.replace(" (proposed)", ""), "operation": op, "description": desc}, "mappings": maps}
    if keys: b["destination"]["keys"] = keys
    return b

