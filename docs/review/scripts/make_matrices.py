def col(t, c):
    if not t or not c or t not in S: return None
    return next((x for x in S[t]['columns'] if x['name'] == c), None)
def uref(name):
    rev = json.load(open(locate(name, R)['src']))['revisions'][-1]['revision']
    return f"{name.replace('UISS_', '')} rev {rev}"
esc = lambda s: str(s).replace('|', '/').replace('\n', ' ')

# 06 database mapping matrix
L = ['# 06 - Database Mapping Matrix (UI field -> ELIPS column)', '',
     'Generated by `scripts/make_matrices.py` from `db-mapping/*.json`. Type / mandatory come from the DDL (`docs/db/schema.json`).',
     'Evidence: **Schema** = column exists with this type; **Code** = rule module named in "API/Backend"; link UI -> table is *Inferred* unless status Verified. No sample data was available.', '',
     '| Module | Screen | UI Field | Action/Function | API/Backend | DB Table | DB Column | Data Type | Mandatory | Evidence | Status |',
     '|---|---|---|---|---|---|---|---|---|---|---|']
n06 = 0
for name, m in MAPS.items():
    mod, scr, fids, code, api = META[name]
    for f in m['fields']:
        c = col(f.get('table'), f.get('column'))
        L.append(f"| {mod} | {scr} | {esc(f['ui'])} | {esc(f.get('rw', '-'))} {esc(f.get('mapping', '-'))} | {api} | {f.get('table') or 'TBD'} | {f.get('column') or 'TBD'} | "
                 f"{c['type'] if c else '-'} | {('Y' if not c['null'] else 'N') if c else '-'} | {esc(f.get('evidence', ''))}{'; ' + esc(f['note']) if f.get('note') else ''} | {f.get('status')} |")
        n06 += 1
open(os.path.join(R, 'docs/review/06-database-mapping-matrix.md'), 'w').write('\n'.join(L) + f'\n\nRows: {n06}.\n')

